import assert from 'node:assert/strict';
import fs from 'node:fs';
const root = 'https://www.banhalmi.art';
const cover='/assets/img/books/book-meses-konyv/cover.webp';
const media=fs.readFileSync('.'+cover);
assert.equal(media.subarray(0,4).toString('ascii'),'RIFF','Cover must be a committed RIFF file');
assert.equal(media.subarray(8,12).toString('ascii'),'WEBP','Cover must be the user-supplied locally hosted WebP');
assert.ok(media.length>3000,'Cover must contain actual book artwork');

const routes = ['/books/book-meses-konyv.html','/hu/books/book-meses-konyv.html','/de-at/books/book-meses-konyv.html'];
const home = ['index.html','hu/index.html','de-at/index.html'];
const langs = ['en','hu-HU','de-AT'];
const translatedTitles = ['Fabulous Book','Mesés könyv','Fabelhaftes Buch'];
const sitemap = fs.readFileSync('sitemap.xml','utf8');
const registry = JSON.parse(fs.readFileSync('archive-record-registry.json','utf8'));
assert.equal(registry.records.length,75,'Five book records add three language variants');
for (let i=0; i<3; i++) {
 const route=routes[i], html=fs.readFileSync('.'+route,'utf8'),url=root+route;
 assert.ok(html.includes('rel="canonical" href="'+url+'"'),route+' canonical mismatch');
 for(let j=0;j<3;j++) assert.ok(html.includes('hreflang="'+langs[j]+'" href="'+root+routes[j]+'"'),route+' hreflang '+langs[j]);
 assert.ok(sitemap.includes('<loc>'+url+'</loc>'),route+' not in sitemap');
 assert.ok(html.includes('<h1>'+translatedTitles[i]+'</h1>'), 'Localized book heading missing');
 assert.ok(html.includes('<title>'+translatedTitles[i]), 'Localized page title missing');
 assert.ok(html.includes('src="'+cover+'"'),'Book hero must show uploaded cover');
 assert.ok(html.includes('property="og:image" content="'+root+cover+'"'),'OG cover missing');
 assert.ok(html.includes('name="twitter:image" content="'+root+cover+'"'),'Twitter cover missing');
 assert.ok(html.includes('https://bookberry.hu/termek/meses-konyv/'),'Publisher reference missing');
 assert.ok(html.includes('https://www.wikidata.org/wiki/Q138667343'),'Wikidata missing');
 assert.ok(!html.includes('webaruhaz.rozsavolgyi.hu') && !html.includes('lira.hu/hu/antikvar/'), 'Retired antiquarian deep links must not be exposed');
 assert.ok(html.includes('Hayden Moore')&&html.includes('Carol Souya')&&html.includes('Becca Prior'),'Authors missing');
 assert.ok(html.includes('Norbert Bánhalmi')||html.includes('Bánhalmi Norbert'),'Photographer missing');
 assert.ok(!html.includes('book-menopauza-szexi/cover'),'Unrelated cover cannot be used');
 const m=html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);assert.ok(m);
 const graph=JSON.parse(m[1])['@graph'],book=graph.find(x=>x['@type']==='Book');
 assert.equal(book.name,'Mesés könyv', 'Original bibliographic title must be retained');
 if(i!==1) assert.ok(book.alternateName?.includes(translatedTitles[i]), 'Translated Book schema name missing');
 assert.equal(book.isbn,'9786156030047');assert.equal(book.numberOfPages,160);
 assert.equal(book.datePublished,'2019-11-23');assert.equal(book.url,url);
 assert.deepEqual(book.author.map(x=>x.name),['Hayden Moore','Carol Souya','Becca Prior']);
 assert.equal(book.contributor[0]['@id'],'https://www.banhalmiphotography.com/about/');
 assert.equal(book.publisher.name,'newkids');
 assert.equal(book.image['@id'],root+cover+'#cover','Book schema cover mismatch');
 assert.ok(graph.some(x=>x['@type']==='ImageObject'&&x['@id']===root+cover+'#cover'),'ImageObject missing');
 assert.ok(book.sameAs.includes('https://www.wikidata.org/wiki/Q138667343'));
 const archive=registry.records.find(x=>x.canonicalUrl===url);assert.ok(archive);
 assert.equal(archive.presenceResearchPeriod,'IV');
 assert.ok(html.includes('record-period__no">IV'));
  const prefix=i===0?'':i===1?'hu/':'de-at/';
 const curator=fs.readFileSync(prefix+'curators.html','utf8');
 const iv=curator.split('id="period-iv"')[1]?.split('</article>')[0];
 const v=curator.split('id="period-v"')[1]?.split('</article>')[0];
 assert.ok(iv?.includes('href="/'+prefix+'books/book-meses-konyv.html"'),'Mesés must be linked from oeuvre period IV');
 assert.ok(v?.includes('href="/'+prefix+'books/book-menopauza-szexi.html"'),'Menopause book must be linked from oeuvre period V');
const homepage=fs.readFileSync(home[i],'utf8').split('id="books"')[1]?.split('</section>')[0];
 assert.ok(homepage,'Book list missing');
 assert.equal((homepage.match(/<div class="card">/g)||[]).length,5);
 const n2018=homepage.indexOf('<span class="yr">2018</span>'),n2019=homepage.indexOf('<span class="yr">2019</span>'),n2026=homepage.indexOf('<span class="yr">2026</span>');
 assert.ok(n2018>=0&&n2018<n2019&&n2019<n2026,'Book order not chronological');
 assert.ok(homepage.includes('href="books/book-meses-konyv.html"'));
 assert.ok(homepage.includes(translatedTitles[i]), 'Localized homepage book title missing');
}
assert.ok(fs.readFileSync('ai.txt','utf8').includes(root+routes[0]));
console.log('Mesés könyv: 3-language authorship, period IV, 5-book chronological list, schema and sitemap PASS');
